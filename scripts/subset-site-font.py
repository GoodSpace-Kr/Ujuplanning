"""Optional offline font preparation (fonttools + brotli).

Keep the original licensed font as a fallback for future copy and form inputs.
The renamed subset contains the characters used by this repository today.
"""
import hashlib
from pathlib import Path
from fontTools import subset
from fontTools.ttLib import TTFont

root = Path(__file__).resolve().parent.parent
font = TTFont(root / "public/fonts/pretendard-1.3.9/PretendardVariable.woff2")
text = ''.join(chr(i) for i in range(32, 256))
for directory in ['app', 'components', 'lib']:
    for path in (root / directory).rglob('*'):
        if path.suffix in ['.tsx', '.ts', '.css', '.json']:
            text += path.read_text()
options = subset.Options()
options.flavor = 'woff2'
options.name_IDs = ['*']
subsetter = subset.Subsetter(options=options)
subsetter.populate(text=text)
subsetter.subset(font)
# OFL reserves the original family name for unmodified versions.
for record in font['name'].names:
    if record.nameID in {1, 3, 4, 6, 16, 17, 25}:
        record.string = record.toUnicode().replace('Pretendard', 'UjuText').encode(record.getEncoding())
destination = root / 'public/fonts/pretendard-1.3.9/UjuText.woff2'
font.save(destination)
data = destination.read_bytes()
name = f'UjuText-{hashlib.sha256(data).hexdigest()[:12]}.woff2'
destination.rename(destination.with_name(name))
(root / 'app/site-font.css').write_text(f'''/* Generated by scripts/subset-site-font.py; OFL license is shipped beside the font. */
@font-face {{
  font-family: 'UjuText';
  font-style: normal;
  font-weight: 100 900;
  font-display: swap;
  src: url('/fonts/pretendard-1.3.9/{name}') format('woff2');
}}
''')
print(name, len(data))
